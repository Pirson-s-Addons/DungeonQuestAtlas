-- (Core/Core.lua) copia en L el elegido, sobre el ingles. Asi la ventana se
-- puede ver en cualquier idioma sin cambiar el del juego.
ns.LOCALES = {}
function ns.NewLocale(...)
    local texts = {}
    for _, code in ipairs({ ... }) do ns.LOCALES[code] = texts end
    return texts
end

